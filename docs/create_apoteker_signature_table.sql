IF OBJECT_ID(N'dbo.APOTEKER_TANDA_TANGAN_BMHP', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.APOTEKER_TANDA_TANGAN_BMHP (
        transaction_id VARCHAR(50) NOT NULL,
        penerima_nama NVARCHAR(100) NOT NULL CONSTRAINT DF_APOTEKER_TT_PENERIMA_NAMA DEFAULT N'',
        penerima_tanda_tangan NVARCHAR(MAX) NOT NULL CONSTRAINT DF_APOTEKER_TT_PENERIMA_TTD DEFAULT N'',
        penyerah_nama NVARCHAR(100) NOT NULL CONSTRAINT DF_APOTEKER_TT_PENYERAH_NAMA DEFAULT N'',
        penyerah_tanda_tangan NVARCHAR(MAX) NOT NULL CONSTRAINT DF_APOTEKER_TT_PENYERAH_TTD DEFAULT N'',
        updated_at DATETIME2 NOT NULL CONSTRAINT DF_APOTEKER_TT_UPDATED_AT DEFAULT SYSUTCDATETIME(),
        CONSTRAINT PK_APOTEKER_TANDA_TANGAN_BMHP PRIMARY KEY CLUSTERED (transaction_id)
    );
END;
